/** @returns {import('./exportToExcel').ColumnDef[] | null} */
export function resolveExportColumns(module, label) {
  if (!module) return null;
  const meta = MODULE_EXPORT_META[module];
  const presetKey = meta?.preset || module;
  const fn = PRESET_BUILDERS[presetKey];
  if (fn) return fn(label || meta?.defaultLabel);
  const cols = MODULE_COLUMNS[module];
  return cols || null;
}

